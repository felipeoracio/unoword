const assert=require('node:assert/strict');
module.exports=async({page,canvas,documents,requests,errors,projectNetwork})=>{
 const home=page.locator('.uw-studio-sidebar').getByRole('link',{name:'Home',exact:true});
 const put=()=>page.waitForRequest(r=>r.method()==='PUT'&&/\/api\/workspace\/documents\/[^/]+$/.test(new URL(r.url()).pathname));
 let releaseFirst,releaseSecond;
 projectNetwork.saveGate=new Promise(resolve=>releaseFirst=resolve);
 const first=put();await canvas.press('ControlOrMeta+End');await page.keyboard.type(' First queued edit.');await first;
 await home.click();await page.locator('.uw-studio-departure').waitFor();
 await canvas.press('ControlOrMeta+End');await page.keyboard.type(' Second queued edit.');
 projectNetwork.saveGate=new Promise(resolve=>releaseSecond=resolve);
 const second=put();releaseFirst();await second;
 await canvas.press('ControlOrMeta+End');await page.keyboard.type(' Final queued edit.');
 const expected=await canvas.evaluate(el=>el.editor.getJSON());
 projectNetwork.saveGate=null;releaseSecond();
 await page.waitForURL('**/app',{timeout:15000});await page.getByTestId('studio-home').waitFor();
 assert.deepEqual([...documents.values()][0].content,expected,'all queued edits are saved before leaving');
 await page.locator('.uw-studio-sidebar').getByRole('link',{name:'Write',exact:true}).click();
 await canvas.waitFor();
 assert.equal((await canvas.innerText()).includes('Final queued edit.'),true,'reopening restores the latest automatically saved sentence');
 await page.waitForFunction(()=>document.querySelector('.uw-editor-save')?.textContent.includes('All changes saved'));
 let releaseRead;
 projectNetwork.indexGate=new Promise(resolve=>releaseRead=resolve);
 const reading=page.waitForRequest(r=>r.method()==='GET'&&new URL(r.url()).pathname==='/api/workspace/documents');
 await page.evaluate(()=>window.dispatchEvent(new Event('focus')));await reading;
 const start=requests.length;
 await page.locator('.uw-studio-sidebar').getByRole('link',{name:'Library',exact:true}).click();
 await page.waitForURL('**/library');
 projectNetwork.indexGate=null;releaseRead();await page.getByTestId('studio-library').waitFor();
 assert.equal(requests.slice(start).some(r=>/^\/workspace\/documents\/[^/]+$/.test(r.key)&&r.method==='PUT'),false,'clean navigation does not create new document writes');
 assert.deepEqual(errors,[]);
 console.log('PASS navigation drains overlapping autosaves; latest writing reopens intact; clean navigation stays available');
};
