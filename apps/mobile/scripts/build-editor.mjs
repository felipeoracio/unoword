import { build } from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
const { outputFiles } = await build({
  entryPoints: ["editor/editor.ts"],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  minify: true,
  target: "safari16",
  nodePaths: ["./node_modules"],
  alias: {
    "@tiptap/core": new URL("../node_modules/@tiptap/core", import.meta.url)
      .pathname,
  },
  legalComments: "none",
});
const script = outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; connect-src 'none'; frame-src 'none'; base-uri 'none'; form-action 'none'"><style>
:root{--bg:#fff;--fg:#0B1B4D;--muted:#667694}html[data-theme=dark]{--bg:#132036;--fg:#F0F5FF;--muted:#A7B8D4}*{box-sizing:border-box}html,body{margin:0;background:var(--bg);color:var(--fg);font:18px/1.75 -apple-system,BlinkMacSystemFont,sans-serif;overflow-wrap:break-word}body{padding:18px 22px 120px}.tiptap{min-height:70vh;outline:none;max-width:740px;margin:auto}.tiptap p{margin:0 0 1em}.tiptap h1{font-size:2em;line-height:1.3}.tiptap h2{font-size:1.5em}.tiptap h3{font-size:1.2em}.tiptap img{max-width:100%;height:auto;border-radius:10px}.tiptap a{color:#0866FF}.tiptap blockquote{border-left:3px solid #0866FF;padding-left:16px;margin-left:0}.tiptap hr{border:0;border-top:1px solid #BDCEEA}.ProseMirror-selectednode{outline:2px solid #0866FF}@media(min-width:800px){body{padding:30px 60px 150px}}
</style></head><body><div id="editor"></div><script>${script}</script></body></html>`;
mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/editor-html.ts",
  "// Generated by npm run editor:build; no external network dependencies.\nexport const EDITOR_HTML=" +
    JSON.stringify(html) +
    ";\n",
);
writeFileSync("src/generated/editor.html", html);
console.log(
  "Bundled offline rich-text editing canvas:",
  Buffer.byteLength(html),
  "bytes",
);
